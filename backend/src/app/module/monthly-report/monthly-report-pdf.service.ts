@Injectable()
export class MonthlyReportPdfService {
  async render(
    snapshot: MonthlyReportSnapshot,
    locale: ReportLocale,
    personalMember?: MonthlyReportMemberSnapshot,
  ): Promise<Buffer> {
    const doc = new PDFDocument({
      size: 'A4',
      layout: 'landscape',
      margin: 42,
      bufferPages: true,
      info: {
        Title: `${snapshot.mess.name} - ${COPY[locale].report}`,
        Author: 'MessZen',
      },
    });
    const chunks: Buffer[] = [];
    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    const completed = new Promise<Buffer>((resolve, reject) => {
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', reject);
    });

    if (locale === 'bn') {
      doc.registerFont(
        'Report',
        require.resolve(
          '@expo-google-fonts/noto-sans-bengali/400Regular/NotoSansBengali_400Regular.ttf',
        ),
      );
    } else {
      doc.registerFont('Report', 'Helvetica');
    }

    const copy = COPY[locale];
    const money = (value: number) =>
      new Intl.NumberFormat(locale === 'bn' ? 'bn-BD' : 'en-BD', {
        style: 'currency',
        currency: snapshot.mess.currency || 'BDT',
        maximumFractionDigits: 2,
      }).format(value);
    const number = (value: number) =>
      new Intl.NumberFormat(locale === 'bn' ? 'bn-BD' : 'en-BD', {
        maximumFractionDigits: 2,
      }).format(value);
    const monthLabel = new Intl.DateTimeFormat(
      locale === 'bn' ? 'bn-BD' : 'en-US',
      { month: 'long', year: 'numeric', timeZone: 'UTC' },
    ).format(new Date(snapshot.month));

    doc.font('Report');
    this.drawHeader(doc, snapshot.mess.name, monthLabel, copy.report, copy.finalized);

    this.drawSectionTitle(doc, copy.messSummary);
    this.drawMetricGrid(doc, [
      [copy.totalMembers, number(snapshot.summary.totalMembers)],
      [copy.totalMeals, number(snapshot.summary.totalMeals)],
      [copy.totalExpense, money(snapshot.summary.totalExpense)],
      [copy.totalDeposit, money(snapshot.summary.totalDeposit)],
      [copy.mealRate, money(snapshot.summary.mealRate)],
      [copy.totalMessCost, money(snapshot.summary.totalMessCost)],
    ]);

    this.drawSectionTitle(doc, copy.expenseSummary);
    this.drawExpenseSummary(doc, [
      [copy.foodBazar, money(snapshot.expenseSummary.foodBazar)],
      [copy.utility, money(snapshot.expenseSummary.utility)],
      [copy.rentHouse, money(snapshot.expenseSummary.rentHouse)],
      [copy.otherExpenses, money(snapshot.expenseSummary.otherExpenses)],
      [copy.totalExpense, money(snapshot.expenseSummary.totalExpense)],
      [copy.totalMessCost, money(snapshot.expenseSummary.totalMessCost)],
    ]);

    this.drawSectionTitle(doc, copy.memberSummary);
    if (personalMember) {
      doc.fontSize(8.5).fillColor(MUTED).text(copy.personalNote);
      doc.moveDown(0.7);
    }
    this.drawMemberTable(
      doc,
      personalMember ? [personalMember] : snapshot.members,
      {
        member: copy.member,
        meals: copy.meals,
        mealCost: copy.mealCost,
        otherCost: copy.otherCost,
        deposit: copy.deposit,
        balance: copy.balance,
      },
      { money, number, due: copy.due, credit: copy.credit, settled: copy.settled },
    );

    const range = doc.bufferedPageRange();
    for (let index = range.start; index < range.start + range.count; index += 1) {
      doc.switchToPage(index);
      doc
        .font('Report')
        .fontSize(7.5)
        .fillColor(MUTED)
        .text(copy.generatedBy, 42, doc.page.height - 27, { align: 'left' })
        .text(`${index + 1} / ${range.count}`, 42, doc.page.height - 27, {
          align: 'right',
          width: doc.page.width - 84,
        });
    }

    doc.end();
    return completed;
  }

  private drawHeader(
    doc: PDFKit.PDFDocument,
    messName: string,
    month: string,
    title: string,
    status: string,
  ) {
    const top = doc.y;
    doc.roundedRect(42, top, doc.page.width - 84, 70, 8).fill('#FFFFFF');
    doc.rect(42, top, 5, 70).fill(BRAND);
    doc
      .fillColor(INK)
      .fontSize(22)
      .text(title, 62, top + 12, { width: 420 })
      .fontSize(11)
      .fillColor(MUTED)
      .text(`${messName} · ${month}`, 62, top + 43, { width: 500 })
      .fontSize(9)
      .fillColor(BRAND)
      .text(status, doc.page.width - 220, top + 27, { width: 160, align: 'right' });
    doc.y = top + 88;
  }

  private drawSectionTitle(doc: PDFKit.PDFDocument, title: string) {
    if (doc.y > doc.page.height - 130) doc.addPage();
    doc.fontSize(11).fillColor(INK).text(title);
    doc.moveDown(0.55);
  }

  private drawMetricGrid(doc: PDFKit.PDFDocument, metrics: string[][]) {
    const gap = 8;
    const width = (doc.page.width - 84 - gap * 2) / 3;
    const startX = 42;
    const startY = doc.y;
    metrics.forEach(([label, value], index) => {
      const column = index % 3;
      const row = Math.floor(index / 3);
      const x = startX + column * (width + gap);
      const y = startY + row * 48;
      doc.roundedRect(x, y, width, 40, 6).fillAndStroke(SURFACE, LINE);
      doc.fontSize(7.5).fillColor(MUTED).text(label, x + 10, y + 8, { width: width - 20 });
      doc.fontSize(11).fillColor(INK).text(value, x + 10, y + 21, { width: width - 20 });
    });
    doc.y = startY + 104;
  }

  private drawExpenseSummary(doc: PDFKit.PDFDocument, rows: string[][]) {
    const gap = 8;
    const width = (doc.page.width - 84 - gap) / 2;
    const startY = doc.y;
    rows.forEach(([label, value], index) => {
      const column = index % 2;
      const row = Math.floor(index / 2);
      const x = 42 + column * (width + gap);
      const y = startY + row * 31;
      doc.rect(x, y, width, 27).fillAndStroke('#FFFFFF', LINE);
      doc.fontSize(8).fillColor(MUTED).text(label, x + 10, y + 9, { width: width * 0.56 });
      doc.fontSize(8.5).fillColor(INK).text(value, x + width * 0.58, y + 9, {
        width: width * 0.38,
        align: 'right',
      });
    });
    doc.y = startY + 105;
  }

  private drawMemberTable(
    doc: PDFKit.PDFDocument,
    members: MonthlyReportMemberSnapshot[],
    headings: Record<'member' | 'meals' | 'mealCost' | 'otherCost' | 'deposit' | 'balance', string>,
    format: {
      money: (value: number) => string;
      number: (value: number) => string;
      due: string;
      credit: string;
      settled: string;
    },
  ) {
    const widths = [185, 70, 112, 112, 112, 167];
    const labels = [headings.member, headings.meals, headings.mealCost, headings.otherCost, headings.deposit, headings.balance];
    const startX = 42;
    const rowHeight = 29;

    const drawHeader = () => {
      let x = startX;
      labels.forEach((label, index) => {
        doc.rect(x, doc.y, widths[index], rowHeight).fill(BRAND);
        doc.fontSize(7.5).fillColor('#FFFFFF').text(label, x + 7, doc.y + 10, {
          width: widths[index] - 14,
          align: index ? 'right' : 'left',
        });
        x += widths[index];
      });
      doc.y += rowHeight;
    };

    drawHeader();
    members.forEach((member) => {
      if (doc.y + rowHeight > doc.page.height - 42) {
        doc.addPage();
        drawHeader();
      }
      const balanceLabel = member.due > 0
        ? `${format.money(member.due)} ${format.due}`
        : member.credit > 0
          ? `${format.money(member.credit)} ${format.credit}`
          : format.settled;
      const values = [
        member.name,
        format.number(member.totalMeals),
        format.money(member.mealCost),
        format.money(member.otherCost),
        format.money(member.deposit),
        balanceLabel,
      ];
      let x = startX;
      values.forEach((value, index) => {
        doc.rect(x, doc.y, widths[index], rowHeight).fillAndStroke('#FFFFFF', LINE);
        doc.fontSize(7.5).fillColor(index === 5 ? BRAND : INK).text(value, x + 7, doc.y + 10, {
          width: widths[index] - 14,
          align: index ? 'right' : 'left',
          ellipsis: true,
        });
        x += widths[index];
      });
      doc.y += rowHeight;
    });
  }
}
